# Get current age from the user and convert to an integer
current_age = int(input("Enter your current age: "))

# Perform calculations
next_year = current_age + 1
after_5_years = current_age + 5
ago_10_years = current_age - 10

# Display results
print(f"Next year you will be: {next_year}")
print(f"After 5 years you will be: {after_5_years}")
print(f"10 years ago you were: {ago_10_years}")